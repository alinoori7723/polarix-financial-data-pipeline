def map_decision_to_stage(prefix: str, decision: str) -> str:
    norm = (decision or "").strip().upper()
    if norm in ("PASS", "PARTIAL", "FAIL"):
        return f"{prefix}_{norm}"
    return f"{prefix}_FAIL"
